const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const envFile = path.join(rootDir, '.env');
const exampleFile = path.join(rootDir, '.env.example');

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const content = fs.readFileSync(filePath, 'utf-8');
  const vars = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      const value = trimmed.slice(eqIdx + 1).trim();
      vars[key] = value;
    }
  }
  return vars;
}

const fileVars = fs.existsSync(envFile) ? parseEnvFile(envFile) : parseEnvFile(exampleFile);

const config = {
  APP_ENV: process.env.APP_ENV || fileVars.APP_ENV || 'development',
  API_BASE_URL: process.env.API_BASE_URL || fileVars.API_BASE_URL || '/api/v1',
  API_PROXY_TARGET: process.env.API_PROXY_TARGET || fileVars.API_PROXY_TARGET || 'http://localhost:5000',
  PATIENT_PORTAL_URL: process.env.PATIENT_PORTAL_URL || fileVars.PATIENT_PORTAL_URL || 'http://localhost:4300',
  DEFAULT_SOURCE_ID: process.env.DEFAULT_SOURCE_ID || fileVars.DEFAULT_SOURCE_ID || 'f0000000-0000-4000-8000-000000000001',
  BRANCH_UTC_OFFSET: process.env.BRANCH_UTC_OFFSET || fileVars.BRANCH_UTC_OFFSET || '-5',
};

// 1. Write public/env.js (used for runtime browser loading)
const publicDir = path.join(rootDir, 'public');
if (!fs.existsSync(publicDir)) {
  fs.mkdirSync(publicDir, { recursive: true });
}
const envJsContent = `// Auto-generated by scripts/generate-env.js from .env / environment variables.
(function (window) {
  window.__ENV__ = window.__ENV__ || {};
  window.__ENV__.APP_ENV = ${JSON.stringify(config.APP_ENV)};
  window.__ENV__.API_BASE_URL = ${JSON.stringify(config.API_BASE_URL)};
  window.__ENV__.API_PROXY_TARGET = ${JSON.stringify(config.API_PROXY_TARGET)};
  window.__ENV__.PATIENT_PORTAL_URL = ${JSON.stringify(config.PATIENT_PORTAL_URL)};
  window.__ENV__.DEFAULT_SOURCE_ID = ${JSON.stringify(config.DEFAULT_SOURCE_ID)};
  window.__ENV__.BRANCH_UTC_OFFSET = ${JSON.stringify(config.BRANCH_UTC_OFFSET)};
})(typeof window !== 'undefined' ? window : this);
`;
fs.writeFileSync(path.join(publicDir, 'env.js'), envJsContent, 'utf-8');

// 2. Write src/environments/environment.ts (used for build-time and typed TypeScript consumption)
const environmentsDir = path.join(rootDir, 'src', 'environments');
if (!fs.existsSync(environmentsDir)) {
  fs.mkdirSync(environmentsDir, { recursive: true });
}
const envTsContent = `// Auto-generated by scripts/generate-env.js from .env / environment variables.
declare global {
  interface Window {
    __ENV__?: Record<string, string>;
  }
}

const runtimeEnv = typeof window !== 'undefined' ? window.__ENV__ : undefined;

export const environment = {
  production: (runtimeEnv?.['APP_ENV'] ?? ${JSON.stringify(config.APP_ENV)}) === 'production',
  appEnv: runtimeEnv?.['APP_ENV'] ?? ${JSON.stringify(config.APP_ENV)},
  apiBaseUrl: runtimeEnv?.['API_BASE_URL'] ?? ${JSON.stringify(config.API_BASE_URL)},
  apiProxyTarget: runtimeEnv?.['API_PROXY_TARGET'] ?? ${JSON.stringify(config.API_PROXY_TARGET)},
  patientPortalUrl: runtimeEnv?.['PATIENT_PORTAL_URL'] ?? ${JSON.stringify(config.PATIENT_PORTAL_URL)},
  defaultSourceId: runtimeEnv?.['DEFAULT_SOURCE_ID'] ?? ${JSON.stringify(config.DEFAULT_SOURCE_ID)},
  branchUtcOffsetHours: Number(runtimeEnv?.['BRANCH_UTC_OFFSET'] ?? ${JSON.stringify(config.BRANCH_UTC_OFFSET)}),
};
`;
fs.writeFileSync(path.join(environmentsDir, 'environment.ts'), envTsContent, 'utf-8');

console.log('[generate-env] Environment files generated successfully from .env');
